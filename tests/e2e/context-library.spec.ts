import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import { API_URL } from "./environment.mjs";

for (const language of ["zh-CN", "en"])
  test(`work materials are progressive, searchable and fit narrow panels (${language})`, async ({
    page,
    request,
  }) => {
    const chinese = language === "zh-CN";
    const board = (
      await (
        await request.post(`${API_URL}/api/v2/canvases`, {
          data: { title: `Materials ${randomUUID()}`, idempotencyKey: randomUUID() },
        })
      ).json()
    ).node;
    const agent = (
      await (
        await request.post(`${API_URL}/api/v2/nodes`, {
          data: {
            kind: "agent",
            title: "Archivist",
            parentId: board.id,
            agent: { role: "read", persona: "", enabled: false },
            position: { x: 80, y: 80, width: 220, height: 300 },
            idempotencyKey: randomUUID(),
          },
        })
      ).json()
    ).node;
    const serverId = (await (await request.get(`${API_URL}/api/v2/server`)).json()).id;
    await page.addInitScript(
      ({ serverId, canvasId, language }) => {
        localStorage.setItem(`intrica:server:${serverId}:intrica:canvas`, canvasId);
        localStorage.setItem("intrica:language", language);
      },
      { serverId, canvasId: board.id, language },
    );
    const entry = {
      ref: "context:fixture",
      archiveId: "fixture",
      version: 1,
      createdAt: "2026-10-15T01:00:00Z",
      sourceCount: 1,
      excerpt: "Permission review findings",
    };
    let reads = 0,
      failure = true;
    const queries: URLSearchParams[] = [];
    await page.route("**/api/v2/conversations/*/context-library?*", async (route) => {
      reads++;
      if (failure) {
        failure = false;
        await route.fulfill({
          status: 503,
          json: { error: { code: "UNAVAILABLE", message: "Read unavailable" } },
        });
        return;
      }
      const q = new URL(route.request().url()).searchParams;
      queries.push(q);
      const ref = q.get("ref");
      const json = !ref
        ? { kind: "directory", conversationId: "test", archives: [entry], nextOffset: null }
        : ref === entry.ref
          ? {
              ...entry,
              kind: "archive",
              conversationId: "test",
              summary: "Generated overview. Follow up pending access request.",
              summaryCharacters: 60,
              summaryTruncated: false,
              summaryRef: `${entry.ref}:summary`,
              sources: [
                {
                  ref: `${entry.ref}:0`,
                  index: 0,
                  role: "toolResult",
                  hash: "hash",
                  characters: 6100,
                  excerpt: "Permission evidence",
                  matchOffset: null,
                  toolName: "read",
                },
              ],
              nextOffset: null,
            }
          : {
              kind: "source",
              conversationId: "test",
              ref,
              archiveId: "fixture",
              sourceIndex: 0,
              role: "toolResult",
              hash: "hash",
              text: q.get("offset")
                ? "FINAL_EVIDENCE"
                : `SOURCE_START ${"long_reference_".repeat(400)}`,
              offset: Number(q.get("offset") ?? 0),
              offsetUnit: "utf16",
              totalCharacters: 6100,
              nextOffset: q.get("offset") ? null : 6000,
            };
      await route.fulfill({ json });
    });
    await page.goto("/");
    await page.locator(`[data-node-id="${agent.id}"]`).dblclick();
    const materials = page.locator("details.context-library");
    await expect(materials).toBeVisible();
    expect(reads).toBe(0);
    await materials.locator("summary").press("Enter");
    await expect(materials.getByRole("alert")).toBeVisible();
    await materials.getByRole("button", { name: chinese ? "重试" : "Retry", exact: true }).click();
    await expect(materials).toContainText("Permission review findings");
    await materials.getByRole("searchbox").fill("permission");
    await materials.getByRole("button", { name: chinese ? "搜索" : "Search", exact: true }).click();
    await expect.poll(() => queries.at(-1)?.get("query")).toBe("permission");
    await materials.getByRole("button", { name: /Permission review findings/ }).click();
    await expect(materials).toContainText(chinese ? "摘要由模型生成" : "generated by a model");
    await materials.getByRole("button", { name: /Permission evidence/ }).click();
    await expect(materials).toContainText("SOURCE_START");
    await page.setViewportSize({ width: 700, height: 900 });
    const separator = page.getByRole("separator", {
      name: chinese ? "调整侧栏宽度" : "Resize sidebar",
      exact: true,
    });
    for (let i = 0; i < 30 && Number(await separator.getAttribute("aria-valuenow")) > 320; i++)
      await separator.press("ArrowRight");
    expect((await page.locator(".workspace-panel").boundingBox())!.width).toBeCloseTo(320, 0);
    expect(
      await materials.evaluate((element) => element.scrollWidth - element.clientWidth),
    ).toBeLessThanOrEqual(1);
    expect(
      await materials
        .locator("pre")
        .evaluate((element) => element.scrollWidth - element.clientWidth),
    ).toBeLessThanOrEqual(1);
    await materials
      .getByRole("button", { name: chinese ? "继续阅读" : "Continue reading", exact: true })
      .click();
    await expect(materials).toContainText("FINAL_EVIDENCE");
    await materials
      .getByRole("button", { name: chinese ? "返回上一层" : "Go back", exact: true })
      .click();
    await expect(materials).toContainText("SOURCE_START");
    await materials.screenshot({ path: test.info().outputPath(`materials-${language}.png`) });
  });
